const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base='http://127.0.0.1:8765/';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:940},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto(base+'portal.html',{waitUntil:'domcontentloaded'});
  await page.locator('#home-title').waitFor({state:'visible'});
  assert.match(await page.locator('#home-title').innerText(),/Служебный.*портал ФСО/s);
  assert.equal(await page.locator('.nv-hero-photo').count(),1);
  assert.equal(await page.locator('.nv-utility>button').count(),4);
  assert.equal(await page.locator('.nv-service-links>button').count(),4);
  assert.equal(await page.locator('.nv-library-list>button').count(),4);
  assert.equal(await page.locator('.nv-legal-list>button').count(),3);
  assert.equal(await page.locator('#portal-ref-count').count(),1);
  assert.equal(await page.locator('#portal-law-count').count(),1);
  assert.ok(Number(await page.locator('#portal-ref-count').innerText())>0);
  assert.equal(await page.locator('#section-search').count(),1);
  const visibleText=await page.locator('#home-screen').innerText();
  assert.ok(!/\bwiki\b|\bвики\b/i.test(visibleText),'No Wiki branding must remain');
  assert.equal(await page.locator('.wk-catalog-card').count(),0,'Avoid copied wiki category grid');
  let dimensions=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
  assert.ok(dimensions.width<=dimensions.viewport+3,'Desktop horizontal overflow '+JSON.stringify(dimensions));
  const libraryStyle=await page.locator('.nv-library').evaluate(el=>{
    const bg=getComputedStyle(el),title=getComputedStyle(el.querySelector('h2'));
    return {background:bg.backgroundColor,text:title.color,backgroundImage:bg.backgroundImage};
  });
  const rgb=s=>[...s.matchAll(/\d+/g)].map(x=>Number(x[0])).slice(0,3);
  const [br,bg,bb]=rgb(libraryStyle.background);
  const [tr,tg,tb]=rgb(libraryStyle.text);
  assert.ok(br<45&&bg<75&&bb<100,'Knowledge area must be dark navy, not white: '+JSON.stringify(libraryStyle));
  assert.ok(tr>195&&tg>205&&tb>215,'Knowledge title should remain light: '+JSON.stringify(libraryStyle));
  assert.ok(libraryStyle.backgroundImage.includes('gradient'),'Knowledge area should have subtle texture');
  await page.locator('.nv-library').screenshot({path:'/tmp/fso-blue-library.png'});
  await page.screenshot({path:'/tmp/fso-blue-desktop.png',fullPage:true});
  await page.locator('#nv-search-open').click();
  await page.locator('#nv-search-modal').waitFor({state:'visible'});
  await page.locator('#section-search').fill('паспорт');
  await page.locator('#section-search-form button[type="submit"]').click();
  await page.locator('#search-results:not([hidden])').waitFor();
  assert.ok((await page.locator('#search-results').innerText()).length>0);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#nv-search-modal').isVisible(),false);
  await page.locator('.nv-nav [data-page="reference"]').click();
  await page.locator('#reference-list .reference-entry').first().waitFor();
  await page.screenshot({path:'/tmp/fso-blue-reference.png',fullPage:false});
  await page.locator('.nv-more summary').click();
  await page.locator('.nv-more-panel [data-page="detention"]').click();
  await page.locator('#detention-steps .det-step').first().waitFor();
  await page.screenshot({path:'/tmp/fso-blue-detention.png',fullPage:false});
  await page.locator('.nv-nav [data-page="laws"]').click();
  await page.locator('#law-list').waitFor({state:'visible'});
  await page.screenshot({path:'/tmp/fso-blue-laws.png',fullPage:false});
  await page.locator('.nv-nav [data-page="home"]').click();
  await page.setViewportSize({width:390,height:844});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('#home-title').waitFor({state:'visible'});
  dimensions=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
  assert.ok(dimensions.width<=dimensions.viewport+3,'Mobile horizontal overflow '+JSON.stringify(dimensions));
  const navBox=await page.locator('#rail').boundingBox();
  assert.ok(navBox&&navBox.y<5,'Navigation must be at top');
  await page.locator('#nv-menu-button').click();
  assert.equal(await page.locator('#nv-menu-button').getAttribute('aria-expanded'),'true');
  await page.locator('.nv-nav [data-page="reference"]').click();
  await page.locator('#reference-list .reference-entry').first().waitFor();
  assert.equal(await page.locator('#nv-menu-button').getAttribute('aria-expanded'),'false');
  await page.locator('.nv-identity').click();
  await page.locator('#home-screen').waitFor({state:'visible'});
  const mobileLibrary=await page.locator('.nv-library').evaluate(el=>getComputedStyle(el).backgroundColor);
  assert.ok(mobileLibrary.match(/\d+/g).slice(0,3).map(Number).every(x=>x<110),'Mobile library should be dark navy: '+mobileLibrary);
  await page.screenshot({path:'/tmp/fso-blue-mobile.png',fullPage:true});
  assert.deepEqual(errors,[],'Unexpected page errors');
  console.log('PASS: blue FSO portal home, search, sections, desktop/mobile and independent branding');
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
